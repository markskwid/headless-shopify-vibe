import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import {
  buildClientSchema,
  getIntrospectionQuery,
  Kind,
  parse,
  print,
  validate,
} from "graphql";

const storefrontApiVersion = "2026-07";
const projectRoot = resolve(import.meta.dirname, "..");
const documentsRoot = join(
  projectRoot,
  "src",
  "lib",
  "shopify",
  "graphql",
);
const outputPath = join(documentsRoot, "generated", "operations.ts");
const schemaUrl = `https://shopify.dev/storefront-graphql-direct-proxy/${storefrontApiVersion}`;

async function collectTypeScriptFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const path = join(directory, entry.name);

      if (entry.isDirectory()) {
        return entry.name === "generated"
          ? []
          : collectTypeScriptFiles(path);
      }

      return entry.isFile() && entry.name.endsWith(".ts") ? [path] : [];
    }),
  );

  return files.flat();
}

function extractGraphQlDocuments(source) {
  return [...source.matchAll(/`#graphql([\s\S]*?)`/g)].map((match) =>
    match[1].replace(/\$\{[^}]+\}/g, "").trim(),
  );
}

async function fetchStorefrontSchema() {
  const response = await fetch(schemaUrl, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ query: getIntrospectionQuery() }),
  });

  if (!response.ok) {
    throw new Error(
      `Shopify schema request failed with ${response.status} ${response.statusText}.`,
    );
  }

  const payload = await response.json();

  if (!payload?.data || payload.errors?.length) {
    throw new Error(
      payload?.errors?.map((error) => error.message).join(" ") ||
        "Shopify returned no schema data.",
    );
  }

  // Shopify's introspection currently marks one implementation field as
  // deprecated while its interface field is not. The service schema is still
  // authoritative for operation validation, so skip GraphQL 17's stricter
  // schema-self-validation and validate our documents against it directly.
  return buildClientSchema(payload.data, { assumeValid: true });
}

function operationManifest(document) {
  return document.definitions
    .filter(
      (definition) =>
        definition.kind === Kind.OPERATION_DEFINITION && definition.name,
    )
    .map((definition) => ({
      name: definition.name.value,
      kind: definition.operation,
      variables: (definition.variableDefinitions ?? []).map((variable) =>
        print(variable),
      ),
      hash: createHash("sha256").update(print(definition)).digest("hex"),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function renderGeneratedArtifact(operations, documentHash) {
  const serializedOperations = JSON.stringify(
    Object.fromEntries(
      operations.map((operation) => [
        operation.name,
        {
          kind: operation.kind,
          variables: operation.variables,
          hash: operation.hash,
        },
      ]),
    ),
    null,
    2,
  );

  return `/**
 * Generated by npm run graphql:codegen.
 * Do not edit this file manually.
 */

export const SHOPIFY_STOREFRONT_API_VERSION = ${JSON.stringify(storefrontApiVersion)} as const;
export const SHOPIFY_STOREFRONT_DOCUMENT_HASH = ${JSON.stringify(documentHash)} as const;
export const SHOPIFY_STOREFRONT_OPERATIONS = ${serializedOperations} as const;

export type ShopifyStorefrontOperationName =
  keyof typeof SHOPIFY_STOREFRONT_OPERATIONS;
`;
}

const files = await collectTypeScriptFiles(documentsRoot);
const sources = await Promise.all(
  files.map(async (file) => ({
    file,
    source: await readFile(file, "utf8"),
  })),
);
const documents = sources.flatMap(({ file, source }) =>
  extractGraphQlDocuments(source).map((document) => ({ file, document })),
);

if (!documents.length) {
  throw new Error("No #graphql documents were found.");
}

let parsedDocument;

try {
  parsedDocument = parse(documents.map(({ document }) => document).join("\n"));
} catch (error) {
  const sourceList = documents
    .map(({ file }) => relative(projectRoot, file))
    .join(", ");
  throw new Error(`Could not parse GraphQL documents in ${sourceList}.`, {
    cause: error,
  });
}

const schema = await fetchStorefrontSchema();
const validationErrors = validate(schema, parsedDocument);

if (validationErrors.length) {
  throw new Error(
    `Shopify GraphQL validation failed:\n${validationErrors
      .map((error) => `- ${error.message}`)
      .join("\n")}`,
  );
}

const printedDocument = print(parsedDocument);
const documentHash = createHash("sha256")
  .update(printedDocument)
  .digest("hex");
const operations = operationManifest(parsedDocument);

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  renderGeneratedArtifact(operations, documentHash),
  "utf8",
);

process.stdout.write(
  `Validated and generated ${operations.length} Shopify Storefront operations for ${storefrontApiVersion}.\n`,
);
